export function exportDesignSystem(projectDir, tokens, name = 'Design System') {
  const resolved = path.resolve(String(projectDir || process.cwd()));
  fs.mkdirSync(resolved, { recursive: true });
  const cssPath = path.join(resolved, 'tokens.css');
  const mdPath = path.join(resolved, 'DESIGN_SYSTEM.md');
  fs.writeFileSync(cssPath, generateTokensCss(tokens, name), 'utf8');
  fs.writeFileSync(mdPath, generateDesignSystemMd(tokens, name), 'utf8');
  return { projectDir: resolved, cssPath, mdPath };
}
