export function scanProjectTokens(projectDir) {
  const resolved = path.resolve(String(projectDir || process.cwd()));
  if (!fs.existsSync(resolved)) {
    throw new Error(`Directory not found: ${resolved}`);
  }

  const foundVars = {};
  const scannedFiles = [];
  const skipDirs = new Set(['node_modules', '.git', 'dist', 'build', '.next']);

  function walk(dir, depth = 0) {
    if (depth > 3 || scannedFiles.length >= 25) return;
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.isDirectory()) {
        if (!skipDirs.has(e.name)) walk(path.join(dir, e.name), depth + 1);
      } else if (e.isFile() && /\.(css|scss)$/i.test(e.name)) {
        const full = path.join(dir, e.name);
        try {
          const text = fs.readFileSync(full, 'utf8');
          const matches = text.matchAll(/--([a-zA-Z0-9_-]+)\s*:\s*([^;}{]+);/g);
          let count = 0;
          for (const m of matches) {
            const key = `--${m[1]}`;
            const val = m[2].trim();
            if (!foundVars[key] && val.length < 100) {
              foundVars[key] = val;
              count += 1;
            }
          }
          if (count > 0) scannedFiles.push(path.relative(resolved, full).replace(/\\/g, '/'));
        } catch {
          // ignore
        }
      }
    }
  }

  walk(resolved);
  return {
    projectDir: resolved,
    scannedFiles,
    variables: foundVars,
    count: Object.keys(foundVars).length,
  };
}

export function generateTokensCss(tokens, name = 'Custom Design System') {
  return `/* ${name} — Generated by Project Studio */
:root {
  --color-primary: ${tokens.primary};
  --color-secondary: ${tokens.secondary};
  --color-bg: ${tokens.background};
  --color-surface: ${tokens.surface};
  --color-text: ${tokens.text};
  --color-muted: ${tokens.muted};
  --color-border: ${tokens.border};
  --color-success: ${tokens.success};
  --color-warning: ${tokens.warning};
  --color-danger: ${tokens.danger};
  --radius-md: ${tokens.radius};
  --font-sans: ${tokens.fontSans};
  --font-mono: ${tokens.fontMono};
}
`;
}

